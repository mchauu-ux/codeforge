export const LEARNING_PATHS: LearningPath[] = RAW_PATHS.map(([title, level, tags]) => {
  const [min, max] = HOURS_BY_LEVEL[level];
  const base = PATH_TITLES.indexOf(title);
  return {
    title,
    level,
    tags,
    courses: 3 + ((base * 7 + tags.length) % 5) + (level === 'Advanced' ? 2 : 0),
    hours: min + ((base * 13) % (max - min + 1)),
  };
});

